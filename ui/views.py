def render_diagnostics_view(
    ai_model: AiModel,
    health: Any,
    caps: Any,
    doc_store: DocStore,
    cache_dir: Path,
) -> None:
    """Render redacted provider health, hardware telemetry, and log tail."""
    st.markdown("## Diagnostics")
    st.caption("Redacted provider health, hardware telemetry, and the tail of the application log.")

    st.markdown("### Provider health")
    st.markdown(
        f"- Status: `{html.escape(str(getattr(health, 'status', 'unknown')))}`\n"
        f"- Message: {html.escape(redact_text(str(getattr(health, 'message', '') or 'n/a')))}\n"
        f"- Active model: `{html.escape(str(getattr(caps, 'model_name', 'unknown')))}`\n"
        f"- Mode: {'Local' if getattr(caps, 'is_local', True) else 'Cloud'}\n"
        f"- Context window: {getattr(caps, 'context_window', 0)} tokens"
    )

    st.markdown("### Native runtime")
    for line in runtime_details():
        st.markdown(f"- {html.escape(line)}")

    st.markdown("### Hardware")
    gpu_info = get_gpu_memory_info()
    proc_info = get_process_memory_info()
    vram = (
        f"{gpu_info.get('used_mb', 0.0):.0f} / {gpu_info.get('total_mb', 0.0):.0f} MB"
        if gpu_info
        else "CPU-only (no NVIDIA GPU reported)"
    )
    st.markdown(f"- Process RAM: {proc_info.get('rss_mb', 0.0):.0f} MB\n- GPU VRAM: {vram}")
    st.markdown(f"- Documents: {doc_store.count_documents()} · Cached summaries: {doc_store.count_summaries()}")

    st.markdown("### Application log (redacted tail)")
    log_file = Path(__file__).resolve().parent.parent / "data" / "logs" / "app.log"
    if not log_file.exists():
        st.caption("No application log file found.")
        return
    try:
        tail = log_file.read_text(encoding="utf-8", errors="replace").splitlines()[-40:]
    except Exception as log_err:  # noqa: BLE001 - diagnostics must not crash the page
        st.error(f"Could not read the application log: {redact_text(str(log_err))}")
        return
    st.code("\n".join(redact_text(line) for line in tail), language="text")


