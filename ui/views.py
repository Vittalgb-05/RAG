def render_chat_view(
    ai_model: AiModel,
    health: Any,
    caps: Any,
    doc_store: DocStore,
    cache_dir: Path | None = None,
) -> None:
    """Render modern evidence-grounded chatbot workspace with chronological flow and popover inserter."""
    cache_dir = cache_dir or (Path(__file__).resolve().parent.parent / ".cache")
    is_healthy = bool(health.status == "healthy")
    has_docs = bool(st.session_state.document_metadata or st.session_state.indexed_files)

    # Focus Filter Dropdown (All Documents vs specific file)
    doc_metadata = st.session_state.get("document_metadata", {})
    doc_options = ["all"] + list(doc_metadata.keys())

    def _doc_label(key: str) -> str:
        if key == "all":
            return "All Documents"
        meta = doc_metadata.get(key, {})
        return f"{meta.get('filename', key)} (p. {meta.get('pages', 1)})"

    current_filter_idx = 0
    if "selected_chat_doc" in st.session_state and st.session_state.selected_chat_doc in doc_options:
        current_filter_idx = doc_options.index(st.session_state.selected_chat_doc)

    # Chat Header Toolbar: Focus Selector + Single-Button File Inserter
    col_filter, col_insert = st.columns([3.5, 1.5])
    with col_filter:
        selected_filter = st.selectbox(
            "Focus Context",
            options=doc_options,
            format_func=_doc_label,
            index=current_filter_idx,
            key="chat_focus_filter",
            label_visibility="collapsed",
            help="Filter responses across all uploaded PDFs or restrict to a single document.",
        )
        st.session_state.selected_chat_doc = selected_filter

    with col_insert:
        render_file_upload_button(
            doc_store=doc_store,
            ai_model=ai_model,
            cache_dir=cache_dir,
            label="Attach PDF",
            key_suffix="chat",
            use_container_width=True,
        )

    # Empty State Hero when conversation has not started
    if not st.session_state.chat_history:
        st.markdown("<div style='height: 2rem;'></div>", unsafe_allow_html=True)
        brand_svg = get_brand_mark_svg(size=36)
        hero_html = (
            f'<div style="text-align: center; margin-bottom: 2rem;">'
            f'<div style="margin-bottom: 0.75rem; display: inline-flex; opacity: 0.9;">{brand_svg}</div>'
            f'<div style="font-size: 1.5rem; font-weight: 600; color: #F4F4F5; margin-bottom: 0.35rem; letter-spacing: -0.02em;">'
            f"What would you like to understand?</div>"
            f'<div style="font-size: 0.875rem; color: #A1A1AA; max-width: 480px; margin: 0 auto; line-height: 1.5;">'
            f"Ask questions, extract data, analyze figures, and verify findings with page-grounded citations.</div>"
            f"</div>"
        )
        if hasattr(st, "html"):
            st.html(hero_html)
        else:
            st.markdown(hero_html, unsafe_allow_html=True)

        if not has_docs:
            st.info("Upload a PDF document to begin asking questions.")
        else:
            # Quick suggestion prompts for instant analysis
            s1, s2, s3, s4 = st.columns(4)
            with s1:
                if st.button("Summarize thesis", use_container_width=True):
                    st.session_state._queued_prompt = (
                        "Summarize the core thesis and key findings of the document in detail."
                    )
                    st.rerun()
            with s2:
                if st.button("Extract key data", use_container_width=True):
                    st.session_state._queued_prompt = (
                        "What are the key tables, numbers, and quantitative data reported?"
                    )
                    st.rerun()
            with s3:
                if st.button("Explain methodology", use_container_width=True):
                    st.session_state._queued_prompt = "Explain the methodology and approach used in this document."
                    st.rerun()
            with s4:
                if st.button("Risks and limits", use_container_width=True):
                    st.session_state._queued_prompt = "What risks, limitations, or open questions are noted?"
                    st.rerun()

    st.markdown("<div style='height: 0.5rem;'></div>", unsafe_allow_html=True)

    # -------------------------------------------------------------
    # Chronological Conversation Feed (Oldest to Newest)
    # -------------------------------------------------------------
    allow_ext = bool(st.session_state.get("cloud_mode", False) and st.session_state.get("user_consented", False))

    for message in st.session_state.chat_history:
        role = message.get("role", "user")
        with st.chat_message(role):
            raw_content = message.get("content", "")

            if role == "assistant":
                # Check for malicious prompt injection echo
                if message.get("injection_detected"):
                    st.error(
                        "Response blocked — adversarial prompt injection directive detected in output. "
                        "Grounding check failed for security."
                    )
                else:
                    st.markdown(sanitize_display_markdown(raw_content, allow_external=allow_ext))

                v_data = message.get("verification")
                snippets = message.get("snippets", [])
                if snippets:
                    cited_ranks = set((v_data or {}).get("cited_ranks") or [])
                    auto_ranks = set((v_data or {}).get("auto_attributed_ranks") or [])
                    cited_snippets = (
                        [s for s in snippets if s.get("rank") in cited_ranks] if cited_ranks else snippets[:3]
                    )

                    # Render ChatGPT-style citation pills
                    pills = [
                        render_chatgpt_citation_pill(
                            filename=s.get("filename", "doc"),
                            page=s.get("page", 1),
                            excerpt=s.get("content", ""),
                            rank=s.get("rank"),
                            auto_attributed=s.get("rank") in auto_ranks,
                        )
                        for s in cited_snippets
                    ]
                    if pills:
                        pill_html = (
                            f'<div style="margin-top: 0.5rem; margin-bottom: 0.35rem; display: flex; flex-wrap: wrap; gap: 0.35rem;">'
                            f"{''.join(pills)}</div>"
                        )
                        if hasattr(st, "html"):
                            st.html(pill_html)
                        else:
                            st.markdown(pill_html, unsafe_allow_html=True)

                    with st.expander(f"Sources ({len(cited_snippets)})", expanded=False):
                        for s in cited_snippets:
                            safe_name = html.escape(s.get("filename", "doc"))
                            p_num = s.get("page", 1)
                            st.markdown(f"**{safe_name} · Page {p_num}**")
                            snippet_text = sanitize_display_markdown(
                                s.get("content", "").strip(), allow_external=allow_ext
                            )
                            st.markdown(f"> {snippet_text}")

                # Subtle calm message footer
                mode_lbl = (
                    f"Cloud ({message.get('model_name', 'API')})"
                    if message.get("is_cloud")
                    else "100% Local (on-device)"
                )
                grounded_lbl = " · Grounded" if (v_data and v_data.get("is_valid")) else ""
                st.markdown(
                    f'<div style="font-size: 0.72rem; color: #71717A; margin-top: 0.35rem;">{mode_lbl}{grounded_lbl}</div>',
                    unsafe_allow_html=True,
                )
            else:
                st.markdown(sanitize_display_markdown(raw_content, allow_external=allow_ext))

    # -------------------------------------------------------------
    # Chat Input Box & Active Generation Handling
    # -------------------------------------------------------------
    input_placeholder = (
        "Ask a question about the document... (Press Enter)"
        if is_healthy
        else "Inference backend is offline. Start llama-server or configure Cloud in Settings."
    )
    user_prompt = st.chat_input(
        placeholder=input_placeholder,
        disabled=(not has_docs or not is_healthy),
    )

    effective_prompt = user_prompt or st.session_state.pop("_queued_prompt", None)

    if effective_prompt:
        if not is_healthy:
            st.error(f"Inference engine unavailable: {redact_text(health.message)}")
            return

        # 1. Append user prompt and display immediately
        append_chat_turn({"role": "user", "content": effective_prompt})
        with st.chat_message("user"):
            st.markdown(effective_prompt)

        active_retriever = st.session_state.get("hybrid_retriever") or st.session_state.local_embedding
        chat_service = ChatTurnService(ai_model.validate_response)
        prepared = chat_service.prepare(
            prompt=effective_prompt,
            history_before_turn=st.session_state.chat_history[:-1],
            selected_doc=None if selected_filter == "all" else selected_filter,
            document_metadata=st.session_state.document_metadata,
            retriever=active_retriever,
            context_window=caps.context_window,
        )

        if prepared.intent_mismatch:
            with st.chat_message("assistant"):
                st.warning(
                    "To extract all items across this document, please select a specific "
                    "document from the context filter above, then ask again."
                )
            append_chat_turn(chat_service.intent_mismatch_result(prepared).assistant_turn)
            return

        snippets_data = prepared.snippets

        with st.chat_message("assistant"):
            try:
                response_stream = ai_model.ask_a_question_from_pdf_stream(
                    pdf_path="",
                    prompt=effective_prompt,
                    local_embedding=active_retriever,
                    chat_history=prepared.history,
                    retrieval_result=prepared.retrieval_result,
                    doc_id=prepared.doc_filter,
                )
                stream_placeholder = st.empty()
                response_chunks: list[str] = []
                for token in response_stream:
                    response_chunks.append(token)
                    stream_placeholder.markdown("".join(response_chunks) + "▌")
                full_response = "".join(response_chunks)

                result = chat_service.finalize(
                    prepared,
                    full_response,
                    truncation_warning=dict(getattr(ai_model, "last_truncation_warning", {}) or {}),
                    is_cloud=not caps.is_local,
                    model_name=caps.model_name,
                    on_response_ready=stream_placeholder.markdown,
                )

                if result.injection_detected:
                    stream_placeholder.empty()
                    st.error(
                        "Response blocked — adversarial prompt injection directive detected in output. "
                        "Grounding check failed for security."
                    )
                else:
                    if snippets_data:
                        cited_ranks = set(result.cited_ranks or [])
                        auto_ranks = set(result.auto_attributed_ranks or [])
                        cited_snippets = (
                            [s for s in snippets_data if s.get("rank") in cited_ranks]
                            if cited_ranks
                            else snippets_data[:3]
                        )
                        pills = [
                            render_chatgpt_citation_pill(
                                filename=s.get("filename", "doc"),
                                page=s.get("page", 1),
                                excerpt=s.get("content", ""),
                                rank=s.get("rank"),
                                auto_attributed=s.get("rank") in auto_ranks,
                            )
                            for s in cited_snippets
                        ]
                        if pills:
                            pill_html = (
                                f'<div style="margin-top: 0.5rem; margin-bottom: 0.35rem; display: flex; flex-wrap: wrap; gap: 0.35rem;">'
                                f"{''.join(pills)}</div>"
                            )
                            if hasattr(st, "html"):
                                st.html(pill_html)
                            else:
                                st.markdown(pill_html, unsafe_allow_html=True)

                            with st.expander(f"Sources ({len(cited_snippets)})", expanded=False):
                                for s in cited_snippets:
                                    safe_name = html.escape(s.get("filename", "doc"))
                                    p_num = s.get("page", 1)
                                    st.markdown(f"**{safe_name} · Page {p_num}**")
                                    snippet_text = sanitize_display_markdown(s.get("content", "").strip())
                                    st.markdown(f"> {snippet_text}")

                    mode_lbl = f"Cloud ({caps.model_name})" if not caps.is_local else "100% Local (on-device)"
                    grounded_lbl = (
                        " · Grounded" if (result.verification and result.verification.get("is_valid")) else ""
                    )
                    st.markdown(
                        f'<div style="font-size: 0.72rem; color: #71717A; margin-top: 0.35rem;">{mode_lbl}{grounded_lbl}</div>',
                        unsafe_allow_html=True,
                    )

                append_chat_turn(result.assistant_turn)
                # Refresh to re-render full chronological conversation uniformly
                st.rerun()

            except Exception as err:
                error_result = chat_service.error_result(
                    prepared,
                    err,
                    truncation_warning=dict(getattr(ai_model, "last_truncation_warning", {}) or {}),
                    is_cloud=not caps.is_local,
                    model_name=caps.model_name,
                )
                st.error(f"Inference streaming failed: {error_result.error_message}")
                append_chat_turn(error_result.assistant_turn)
                st.rerun()


